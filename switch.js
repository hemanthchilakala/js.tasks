// -------------------------- Calculator ----------------------------
let num1 = 2345;
let num2 = 6789;
let operator = "*"

switch(operator){
    case "+":
        console.log("Result :",num1 + num2);
        break
    case "-":
        console.log("Result :",num1 - num2);
        break
    case "*":
        console.log("Result :",num1 *num2);
        break
    case "/":
        console.log("Result :",num1 / num2);
        break
    case "**":
        console.log("Result :",num1 ** num2);
        break
    case "%":
        console.log("Result :",num1 % num2);
        break
    default:
        console.log("operator not found");
}



